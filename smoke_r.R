args <- commandArgs(TRUE)
.libPaths(c(args[[3]],args[[4]],.libPaths()))
library(datapond)
library(DBI)
options(datapond.registry_url=args[[1]],datapond.cache_dir=args[[2]])
trace('duckdb',where=asNamespace('duckdb'),tracer=quote(config<-modifyList(config,list(threads='1',memory_limit='128MiB',max_temp_directory_size='0B'))),print=FALSE)
stopifnot(identical(dp_list(),'medicaid-enrollment'))
# Released 0.1.0 lacks config: trace only supplies startup resource defaults.
con <- dp_connect('medicaid-enrollment',quiet=TRUE)
tryCatch({
  dbExecute(con,"SET memory_limit='128MiB'")
  dbExecute(con,'SET threads=1')
  dbExecute(con,"SET max_temp_directory_size='0B'")
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM enrollment')$n==11220)
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM monthly_updated')$n==5559)
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM monthly_preliminary')$n==5610)
  stopifnot(dbGetQuery(con,'SELECT count(*) n FROM baseline_enrollment WHERE reporting_month IS NULL')$n==51)
  stopifnot(dbGetQuery(con,"SELECT sum(total_medicaid_and_chip_enrollment) n FROM monthly_preliminary WHERE reporting_period='202607'")$n==72946510)
  stopifnot(nrow(dp_describe(con))==2,nrow(dp_describe(con,table='enrollment'))==47)
  example<-dbGetQuery(con,"SELECT state_abbreviation,total_medicaid_enrollment,total_chip_enrollment FROM monthly_preliminary WHERE reporting_period='202607' ORDER BY state_abbreviation LIMIT 3")
  cat(jsonlite::toJSON(list(passed=TRUE,client='R datapond',version=as.character(packageVersion('datapond')),R=R.version.string,duckdb=as.character(packageVersion('duckdb')),example=example),auto_unbox=TRUE))
},finally=dp_disconnect(con))
